// Static site generator: src/data + src/templates + src/static  →  site/
// Usage: node tools/generate.mjs [https://base-url]   (default: placeholder https://jugnusalon.example)
// No dependencies. site/ is build output (git-ignored); edit src/ instead.
import { readFile, writeFile, mkdir, rm, cp, readdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { makeCtx } from '../src/templates/lib.mjs';
import { INLINE_SCRIPT, csp } from '../src/templates/layout.mjs';
import * as P from '../src/templates/pages.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(ROOT, 'src');
const OUT = join(ROOT, 'site');
export const PLACEHOLDER = 'https://jugnusalon.example';

const baseUrl = (process.argv[2] || PLACEHOLDER).replace(/\/+$/, '');
const json = async (f) => JSON.parse(await readFile(join(SRC, 'data', f), 'utf8'));
const site = await json('site.json');
const { branches, network } = await json('branches.json');
const services = await json('services.json');
const images = await json('images.json');
const instagram = await json('instagram.json');
const { posts, lost } = await json('posts.json');

const inlineScriptHash = `sha256-${createHash('sha256').update(INLINE_SCRIPT).digest('base64')}`;
const ctx = makeCtx({ baseUrl, site, branches, network, services, images, instagram, posts, lostPosts: lost, inlineScriptHash });

// Which widths actually exist per image (originals smaller than a requested width are skipped)
const gFiles = await readdir(join(SRC, 'static/img/g'));
const widths = {};
for (const f of gFiles) { const m = f.match(/^(.+)-(\d+)\.webp$/); if (m) (widths[m[1]] ||= []).push(Number(m[2])); }
ctx.availableWidths = (id) => (widths[id] || []).sort((a, b) => a - b);
for (const im of images) if (!ctx.availableWidths(im.id).length) throw new Error(`No processed files for image ${im.id}. Run python tools/process-images.py`);

// Fresh output
await rm(OUT, { recursive: true, force: true });
await mkdir(OUT, { recursive: true });
await cp(join(SRC, 'static'), join(OUT, 'assets'), { recursive: true });

const pages = [
  P.home(ctx), P.servicesPage(ctx), ...services.categories.map((c) => P.categoryPage(ctx, c)),
  P.aboutPage(ctx), P.galleryPage(ctx), P.branchesPage(ctx), ...branches.map((b) => P.branchPage(ctx, b)),
  P.blogPage(ctx), ...posts.map((p) => P.postPage(ctx, p)), P.contactPage(ctx), P.notFoundPage(ctx),
];
for (const pg of pages) {
  const file = pg.path.endsWith('.html') ? join(OUT, pg.path) : join(OUT, pg.path, 'index.html');
  await mkdir(dirname(file), { recursive: true });
  await writeFile(file, pg.html);
}

// SEO files
const indexable = pages.filter((p) => !p.path.endsWith('.html'));
const today = new Date().toISOString().slice(0, 10);
await writeFile(join(OUT, 'sitemap.xml'), `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${indexable.map((p) => `  <url><loc>${ctx.abs(p.path)}</loc><lastmod>${today}</lastmod></url>`).join('\n')}
</urlset>
`);
await writeFile(join(OUT, 'robots.txt'), site.demo
  ? 'User-agent: *\nAllow: /\n\n# Demo deployment: pages carry noindex. The sitemap is added at launch (tools/demo-mode.mjs off).\n'
  : `User-agent: *\nAllow: /\n\nSitemap: ${ctx.abs('/sitemap.xml')}\n`);
await writeFile(join(OUT, 'site.webmanifest'), JSON.stringify({
  name: site.name, short_name: site.short, start_url: `${ctx.basePath}/`, display: 'browser',
  background_color: '#16301f', theme_color: '#16301f',
  icons: [{ src: `${ctx.basePath}/assets/img/icon-192.png`, sizes: '192x192', type: 'image/png' }, { src: `${ctx.basePath}/assets/img/icon-512.png`, sizes: '512x512', type: 'image/png' }],
}, null, 2));

// Host config inside the publish dir: Netlify + Cloudflare Pages read _headers and _redirects
const policy = csp(inlineScriptHash);
await writeFile(join(OUT, '_headers'), `# Generated by tools/generate.mjs
/assets/img/*
  Cache-Control: public, max-age=2592000
/assets/fonts/*
  Cache-Control: public, max-age=2592000
/assets/css/*
  Cache-Control: public, max-age=86400, must-revalidate
/assets/js/*
  Cache-Control: public, max-age=86400, must-revalidate
/*
${site.demo ? '  X-Robots-Tag: noindex, nofollow\n' : ''}  X-Content-Type-Options: nosniff
  Referrer-Policy: strict-origin-when-cross-origin
  Permissions-Policy: camera=(), microphone=(), geolocation=()
  X-Frame-Options: SAMEORIGIN
  Strict-Transport-Security: max-age=31536000; includeSubDomains
  Content-Security-Policy: ${policy}; frame-ancestors 'self'
`);
const redirects = [['/services/', '/our-services/', 301], ...lost.map((s) => [`/${s}/`, '/blog/', 302])];
await writeFile(join(OUT, '_redirects'), `# Generated by tools/generate.mjs (old WordPress URLs)\n${redirects.map(([f, t, c]) => `${ctx.basePath}${f} ${ctx.basePath}${t} ${c}`).join('\n')}\n`);

console.log(`Generated ${pages.length} pages for ${baseUrl}${site.demo ? ' [DEMO: noindex]' : ''} (CSP ${inlineScriptHash})`);
